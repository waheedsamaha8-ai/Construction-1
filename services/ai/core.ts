export const isStaticHost = (): boolean => {
    if (typeof window === 'undefined') return false;
    const host = window.location.hostname.toLowerCase();
    return (
        host.endsWith('github.io') ||
        host.endsWith('gitlab.io') ||
        host.endsWith('pages.dev') ||
        window.location.protocol === 'file:'
    );
};

export const getCandidateBackendEndpoints = (apiPath: string): string[] => {
    const normalizedPath = apiPath.startsWith('/') ? apiPath : `/${apiPath}`;
    if (isStaticHost()) {
        return CLOUD_RUN_BACKENDS.map((b) => `${b}${normalizedPath}`);
    }
    const currentOrigin = typeof window !== 'undefined' ? window.location.origin : '';
    const fallbacks = CLOUD_RUN_BACKENDS
        .filter((b) => !currentOrigin || b.toLowerCase() !== currentOrigin.toLowerCase())
        .map((b) => `${b}${normalizedPath}`);
    return [normalizedPath, ...fallbacks];
};

export const fetchBackendJson = async <T = any>(
    apiPath: string,
    init?: RequestInit
): Promise<{ data: T; endpoint: string }> => {
    const endpoints = getCandidateBackendEndpoints(apiPath);
    let lastErrorMessage = 'تعذر الاتصال بالخادم';

    for (const endpoint of endpoints) {
        try {
            const res = await fetch(endpoint, init);
            const contentType = (res.headers.get('content-type') || '').toLowerCase();

            // Ignore HTML SPA fallbacks returned by static hosts or SW navigation fallback
            if (contentType.includes('text/html')) {
                lastErrorMessage = 'نقطة الاتصال غير متوفرة على هذا النطاق';
                continue;
            }

            const data = await res.json().catch(() => null);
            if (!res.ok) {
                lastErrorMessage = data?.error || `خطأ من الخادم (${res.status})`;
                if (res.status === 404 || res.status >= 500) {
                    continue;
                }
                return Promise.reject(new Error(lastErrorMessage));
            }

            if (data) {
                return { data: data as T, endpoint };
            }
        } catch (err: any) {
            if (err instanceof Error && err.message && !err.message.includes('Failed to fetch')) {
                lastErrorMessage = err.message;
            } else {
                lastErrorMessage = 'تعذر الوصول إلى خادم الذكاء الاصطناعي';
            }
        }
    }

    throw new Error(lastErrorMessage);
};

// --- SERVER-SIDE GENERATION CALL ---
export const safeGenerateContent = async (
    primaryModel: string,
    params: any
): Promise<{ text: string; usedModel: string; functionCalls?: any[]; response?: any }> => {
    const model = (!primaryModel || primaryModel.includes('preview') || primaryModel.includes('latest'))
        ? MODEL_SMART
        : primaryModel;

    const endpoints = getCandidateBackendEndpoints('/api/gemini/generate');
    let lastError: Error | null = null;

    for (const endpoint of endpoints) {
        try {
            const res = await fetch(endpoint, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                },
                body: JSON.stringify({
                    model,
                    contents: params.contents,
                    config: params.config,
                    cachedContent: params.cachedContent,
                }),
            });

            const contentType = (res.headers.get('content-type') || '').toLowerCase();
            if (contentType.includes('text/html')) {
                lastError = new Error('Endpoint returned HTML instead of JSON');
                continue;
            }

            const data = await res.json().catch(() => null);

            if (!res.ok) {
                const msg = data?.error || `Gemini server request failed (${res.status})`;
                lastError = new Error(msg);
                continue;
            }

            if (data && (typeof data.text === 'string' || data.functionCalls)) {
                return {
                    text: data.text || '',
                    functionCalls: data.functionCalls || undefined,
                    response: data.modelContent ? { candidates: [{ content: data.modelContent }] } : undefined,
                    usedModel: data.usedModel || model,
                };
            }

            lastError = new Error('Empty response from Gemini server');
        } catch (error: any) {
            lastError = error instanceof Error ? error : new Error(String(error || 'Network error'));
            console.warn(`safeGenerateContent endpoint ${endpoint} error:`, lastError.message);
        }
    }

    throw lastError || new Error('Failed to generate content via server');
};

// --- SERVER-SIDE STREAMING CALL (SSE) ---
export const safeGenerateStream = async (
    primaryModel: string,
    params: any,
    onChunk: (text: string) => void
): Promise<string> => {
    const model = (!primaryModel || primaryModel.includes('preview') || primaryModel.includes('latest'))
        ? MODEL_SMART
        : primaryModel;

    const endpoints = getCandidateBackendEndpoints('/api/gemini/stream');
    let res: globalThis.Response | null = null;
    let lastStreamErr = 'Streaming failed';

    for (const streamEndpoint of endpoints) {
        try {
            const candidateRes = await fetch(streamEndpoint, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                },
                body: JSON.stringify({
                    model,
                    contents: params.contents,
                    config: params.config,
                }),
            });
            const ct = (candidateRes.headers.get('content-type') || '').toLowerCase();
            if (ct.includes('text/html') || candidateRes.status === 404) {
                lastStreamErr = `Streaming endpoint unavailable (${candidateRes.status})`;
                continue;
            }
            res = candidateRes;
            break;
        } catch (err: any) {
            lastStreamErr = err?.message || 'Streaming network error';
        }
    }

    if (!res) {
        throw new Error(lastStreamErr);
    }

    let fullText = '';

    if (!res.ok) {
        const errData = await res.json().catch(() => null);
        throw new Error(errData?.error || `Streaming failed with status ${res.status}`);
    }

    if (!res.body) {
        throw new Error('Streaming response body is unavailable');
    }

    const reader = res.body.getReader();
    const decoder = new TextDecoder();
    let buffer = '';

    const processEventBlock = (block: string) => {
        const lines = block.split(/\r?\n/);
        for (const line of lines) {
            if (!line.startsWith('data: ')) continue;
            const rawData = line.slice(6).trim();
            if (!rawData || rawData === '[DONE]') continue;
            let parsed: any;
            try {
                parsed = JSON.parse(rawData);
            } catch {
                continue;
            }
            if (parsed.error) {
                throw new Error(parsed.error);
            }
            if (parsed.text) {
                fullText += parsed.text;
                onChunk(parsed.text);
            }
        }
    };

    while (true) {
        const { done, value } = await reader.read();
        if (done) break;

        buffer += decoder.decode(value, { stream: true });
        const events = buffer.split(/\r?\n\r?\n/);
        buffer = events.pop() || '';

        for (const evt of events) {
            processEventBlock(evt);
        }
    }

    if (buffer.trim()) {
        processEventBlock(buffer);
    }

    return fullText;
};

// --- LIVE API WEBSOCKET CLIENT HELPER ---
export interface LiveSessionCallbacks {
    onAudioChunk?: (base64Audio: string) => void;
    onTextChunk?: (text: string) => void;
    onInputTranscript?: (text: string) => void;
    onOutputTranscript?: (text: string) => void;
    onToolCall?: (toolCall: any) => void;
    onTurnComplete?: () => void;
    onInterrupted?: () => void;
    onStatus?: (status: string) => void;
    onError?: (err: any) => void;
    onClose?: () => void;
}

export interface LiveConnectOptions {
    model?: string;
    systemInstruction?: string;
    voiceName?: string;
}

export const connectLiveApi = (
    callbacks: LiveSessionCallbacks,
    options?: LiveConnectOptions
) => {
    const protocol = window.location.protocol === 'https:' ? 'wss:' : 'ws:';
    const hostPart = isStaticHost()
        ? CLOUD_RUN_BACKENDS[0].replace(/^https?:\/\//, '')
        : window.location.host;
    const wsProtocol = isStaticHost() ? 'wss:' : protocol;

    const queryParams = new URLSearchParams();
    if (options?.model) queryParams.set('model', options.model);
    if (options?.voiceName) queryParams.set('voiceName', options.voiceName);
    if (options?.systemInstruction) queryParams.set('systemInstruction', options.systemInstruction);
    const qs = queryParams.toString();

    const wsUrl = `${wsProtocol}//${hostPart}/api/gemini/live${qs ? `?${qs}` : ''}`;
    const ws = new WebSocket(wsUrl);
    const pendingPayloads: string[] = [];

    const sendJson = (payload: Record<string, any>) => {
        const serialized = JSON.stringify(payload);
        if (ws.readyState === WebSocket.OPEN) {
            ws.send(serialized);
        } else if (ws.readyState === WebSocket.CONNECTING) {
            pendingPayloads.push(serialized);
        }
    };

    ws.onopen = () => {
        while (pendingPayloads.length > 0 && ws.readyState === WebSocket.OPEN) {
            const next = pendingPayloads.shift();
            if (next) ws.send(next);
        }
    };

    ws.onmessage = (event) => {
        try {
            const data = JSON.parse(event.data);
            if (data.audio && callbacks.onAudioChunk) {
                callbacks.onAudioChunk(data.audio);
            }
            if (data.text && callbacks.onTextChunk) {
                callbacks.onTextChunk(data.text);
            }
            if (data.inputTranscript && callbacks.onInputTranscript) {
                callbacks.onInputTranscript(data.inputTranscript);
            }
            if (data.outputTranscript && callbacks.onOutputTranscript) {
                callbacks.onOutputTranscript(data.outputTranscript);
            }
            if (data.toolCall && callbacks.onToolCall) {
                callbacks.onToolCall(data.toolCall);
            }
            if (data.turnComplete && callbacks.onTurnComplete) {
                callbacks.onTurnComplete();
            }
            if (data.interrupted && callbacks.onInterrupted) {
                callbacks.onInterrupted();
            }
            if (data.status && callbacks.onStatus) {
                callbacks.onStatus(data.status);
            }
            if (data.error && callbacks.onError) {
                callbacks.onError(data.error);
            }
        } catch (e) {
            console.error("Failed to parse Live WS message:", e);
        }
    };

    ws.onerror = (err) => {
        if (callbacks.onError) callbacks.onError(err);
    };

    ws.onclose = () => {
        pendingPayloads.length = 0;
        if (callbacks.onClose) callbacks.onClose();
    };

    return {
        sendAudio: (base64Pcm: string, mimeType: string = 'audio/pcm;rate=16000') => {
            sendJson({ audio: base64Pcm, mimeType });
        },
        sendVideo: (base64Image: string, mimeType: string = 'image/jpeg') => {
            sendJson({ video: base64Image, mimeType });
        },
        sendText: (text: string) => {
            sendJson({ text });
        },
        sendToolResponse: (toolResponse: any) => {
            sendJson({ toolResponse });
        },
        close: () => {
            pendingPayloads.length = 0;
            ws.close();
        },
    };
};
